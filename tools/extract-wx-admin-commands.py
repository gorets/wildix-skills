#!/usr/bin/env python3
"""Builds skills/wildix-admin/references/commands.md from the README of wx-admin.

  python3 tools/extract-wx-admin-commands.py <path to>/packages/wx-admin/README.md [skills/wildix-admin/references/commands.md]

The README of wx-admin (https://github.com/gorets/wildix-cli/tree/main/packages/wx-admin) holds the command tables of
every group between the markers `commands:start` and `commands:end`; this copies them, with the version of the CLI.
The output is generated: do not edit it by hand.
"""
import os, re, sys

if len(sys.argv) < 2:
    sys.exit(__doc__)
src = open(sys.argv[1], encoding="utf-8").read()
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "skills/wildix-admin/references/commands.md")
m = re.search(r"\*\*Version ([0-9.]+)\*\*", src)
s, e = src.find("<!-- commands:start"), src.find("<!-- commands:end")
if not m or s < 0 or e < 0:
    sys.exit("the README has no version line or no commands:start/end markers")
body = src[src.index("\n", s) + 1:e].strip()
body = body.replace("\n### ", "\n## ").replace("### wx-admin", "## wx-admin", 1)
with open(out, "w", encoding="utf-8") as f:
    f.write(f"""<!-- Generated by tools/extract-wx-admin-commands.py from the README of wx-admin {m.group(1)}. Do not edit by hand. -->
# wx-admin {m.group(1)} — commands

Every command has `-h`, takes `--pbx HOST`, and prints text or, with `--output json`, JSON. A command marked
`--yes` changes the whole PBX or cannot be undone: see the safety rules in `SKILL.md`.

{body}
""")
print(f"wrote {out}: wx-admin {m.group(1)}, {body.count(chr(10) + '| `wx-admin')} commands")
